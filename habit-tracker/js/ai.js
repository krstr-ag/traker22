    /* --- память о фактах --- */
    if (any('что ты обо мне знаешь', 'что помнишь обо мне', 'что обо мне помнишь')) {
      const facts = [];
      if (mem.name) facts.push(`тебя зовут ${mem.name}`);
      mem.facts.forEach(f => facts.push(f));
      return T('chat', facts.length
        ? `Вот что я запомнил(а):\n${facts.map(f => '• ' + f).join('\n')}\n\nМогу и позабыть, если скажешь «забудь».`
        : 'Пока пусто 😌 Скажи что-нибудь вроде «меня зовут…» или «мне нравится…» — и я запомню.');
    }
    if (any('забудь', 'забыть', 'сотри память')) {
      mem = { name: '', facts: [] }; saveMem();
      return T('chat', '🗑 Готово — память очищена. Начнём заново?');
    }

    /* --- универсальный разговор --- */
    const isQuestion = t.includes('?') ||
      /^(что|как|почему|зачем|где|когда|кто|сколько|можно|стоит|правда|соглас)/.test(t);
    if (isQuestion) return T('chat', pickFree(REFLECT_Q));
