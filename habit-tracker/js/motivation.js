  let favs = HT.get('favQuotes', []);
  let lastIdx = -1;
  const wikiLink = author =>
    `https://ru.wikipedia.org/w/index.php?search=${encodeURIComponent(author)}&ns0=1`;

  const card = document.getElementById('quote-card');
  const favsBox = document.getElementById('quote-favs');
  const favsHead = document.querySelector('#tab-motivation .section-head');
  let favsOpen = false;

  /* плавное появление цитаты (fade + сдвиг); при reduced-motion CSS всё гасит */
  function playIn() {
    if (!card) return;
    card.classList.remove('mot-in');
    void card.offsetWidth;          /* перезапуск анимации */
    card.classList.add('mot-in');
  }

  /* избранные — тихий переключатель «Избранные (n)» */
  function setFavsOpen(open) {
    favsOpen = !!open;
    if (favsBox) favsBox.classList.toggle('open', favsOpen);
    if (favsHead) favsHead.setAttribute('aria-expanded', String(favsOpen));
  }

  if (favsBox) favsBox.classList.add('mot-favs');
  if (favsHead) {
    favsHead.classList.add('mot-favs-head');
    favsHead.setAttribute('role', 'button');
    favsHead.setAttribute('tabindex', '0');
    favsHead.setAttribute('aria-expanded', 'false');
    favsHead.setAttribute('aria-controls', 'quote-favs');
    favsHead.innerHTML =
      '<h3>Избранные <span class="mot-favs-n">(0)</span></h3>' +
      '<span class="mot-favs-caret" aria-hidden="true">▾</span>';
    favsHead.addEventListener('click', () => setFavsOpen(!favsOpen));
    favsHead.addEventListener('keydown', e => {
      if (e.key === 'Enter' || e.key === ' ' || e.key === 'Spacebar') {
        e.preventDefault();
        setFavsOpen(!favsOpen);
      }
    });
  }

  function show(idx, force, silent) {
    if (idx < 0) idx = Math.floor(Math.random() * Q.length);
    if (!force && Q.length > 1) while (idx === lastIdx) idx = Math.floor(Math.random() * Q.length);
    lastIdx = idx;
    const [text, author] = Q[idx];
    document.getElementById('quote-text').textContent = text;
    const a = document.getElementById('quote-author');
    a.textContent = '— ' + author + ' ↗';
    a.href = wikiLink(author);
    const btn = document.getElementById('quote-fav');
    const isFav = favs.includes(idx);
    btn.textContent = isFav ? '★ В избранном' : '☆ В избранное';
    btn.classList.toggle('on', isFav);
    document.getElementById('hdr-sub').textContent = `цитата ${idx + 1} из ${Q.length}`;
    if (!silent) playIn();
    return idx;
  }

  let curIdx = show(Math.floor(Math.random() * Q.length));

  function renderFavs() {
    const box = document.getElementById('quote-favs');
    box.innerHTML = favs.length ? '' : '<p class="tiny">Пока пусто — сохраняйте понравившиеся цитаты ⭐</p>';
    favs.slice().reverse().forEach(i => {
      const [text, author] = Q[i];
      const el = document.createElement('div');
      el.className = 'fav-quote';
      el.innerHTML = `«${text}» <span class="fa">— ${author} · <a href="${wikiLink(author)}" target="_blank" rel="noopener" style="color:var(--acc)">Википедия ↗</a> · <a href="#" data-unfav="${i}" style="color:var(--bad)">убрать</a></span>`;
      box.appendChild(el);
    });
    box.querySelectorAll('[data-unfav]').forEach(a => a.onclick = e => {
      e.preventDefault();
      favs = favs.filter(x => x !== Number(a.dataset.unfav));
      HT.set('favQuotes', favs);
      renderFavs();
      if (curIdx >= 0) show(curIdx, true, true);
    });
    const n = favsHead && favsHead.querySelector('.mot-favs-n');
    if (n) n.textContent = '(' + favs.length + ')';
  }

  document.getElementById('quote-next').onclick = () => { curIdx = show(-1); };
  document.getElementById('quote-fav').onclick = () => {
    const added = !favs.includes(curIdx);
    if (!added) favs = favs.filter(x => x !== curIdx);
    else { favs.push(curIdx); HT.toast('⭐ Цитата сохранена'); }
    HT.set('favQuotes', favs);
    show(curIdx, true, true);
    renderFavs();
    if (added) setFavsOpen(true);   /* сразу показываем сохранённое */
  };

  /* для ИИ: случайная цитата */
  HT.randomQuote = () => {
    const [text, author] = Q[Math.floor(Math.random() * Q.length)];
    return `«${text}» — ${author}`;
  };
  HT.quoteCount = Q.length;

  HT.onShow['tab-motivation'] = () => { renderFavs(); playIn(); };
  renderFavs();
